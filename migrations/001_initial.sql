CREATE TABLE users (sub TEXT PRIMARY KEY, name TEXT NOT NULL, roles TEXT NOT NULL DEFAULT '[]', hospital TEXT);
CREATE TABLE sessions (hash TEXT PRIMARY KEY, sub TEXT NOT NULL REFERENCES users(sub), csrf TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE auth_transactions (hash TEXT PRIMARY KEY, data TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE warrants (id TEXT PRIMARY KEY, data TEXT NOT NULL);
CREATE TABLE jobs (id TEXT PRIMARY KEY, data TEXT NOT NULL);
CREATE TABLE contributions (job TEXT NOT NULL, hospital TEXT NOT NULL, round INTEGER NOT NULL, digest TEXT NOT NULL, data TEXT NOT NULL, PRIMARY KEY(job,hospital,round));
CREATE TABLE ledger (seq INTEGER PRIMARY KEY, data TEXT NOT NULL, previous_hash TEXT NOT NULL, hash TEXT NOT NULL);
CREATE TABLE events (id INTEGER PRIMARY KEY, data TEXT NOT NULL);
